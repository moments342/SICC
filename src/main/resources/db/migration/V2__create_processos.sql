CREATE TABLE processos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_processo VARCHAR(50) NOT NULL UNIQUE,
    tipo_instrumento VARCHAR(80) NOT NULL,
    objeto VARCHAR(500) NOT NULL,
    descricao VARCHAR(1000),
    origem VARCHAR(120),
    natureza VARCHAR(120),
    coordenador VARCHAR(150),
    participes VARCHAR(1000),
    num_contrato VARCHAR(50),
    num_projeto VARCHAR(50),
    vigencia_contrato DATE,
    vigencia_ted DATE,
    valor_total NUMERIC(19, 2),
    status_atual VARCHAR(60) NOT NULL,
    etapa_atual VARCHAR(120),
    publico_simplificado BOOLEAN NOT NULL,
    anexos VARCHAR(1000),
    ativo BOOLEAN NOT NULL,
    data_cadastro DATE NOT NULL,
    usuario_gerente_id BIGINT,
    CONSTRAINT fk_processos_usuario_gerente
        FOREIGN KEY (usuario_gerente_id) REFERENCES usuarios (id)
);
